#!/usr/bin/env python3
"""Build site/public/problems.json and site/seed.sql from problems/*/README.md.

The repo's problem folders are the source of truth; run this after adding or editing one.
seed.sql adds each problem's "In people's words" quotes as starting voices (safe to re-run).
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SITE = ROOT / "site"


def front_matter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    fields = {}
    for line in (m.group(1) if m else "").splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "-")):
            fields[key.strip()] = value.strip()
    return fields, text[m.end():] if m else text


def section(body, name):
    m = re.search(rf"^##\s+{re.escape(name)}\s*$(.*?)(?=^##\s|\Z)", body, re.M | re.S)
    return m.group(1).strip() if m else ""


problems, seeds = [], []
for readme in sorted(ROOT.glob("problems/*/README.md")):
    slug = readme.parent.name
    if slug.startswith("_"):
        continue
    fields, body = front_matter(readme.read_text())
    quotes = [q.strip() for q in re.findall(r"^>\s*(.+)$", section(body, "In people's words"), re.M)]
    questions = [q.strip() for q in re.findall(r"^-\s+(.+)$", section(body, "Open questions"), re.M)]
    problems.append({
        "slug": slug,
        "title": fields.get("title", slug),
        "questions": [q for q in questions if not q.lower().startswith("reminder")],
    })
    seeds += [(slug, q) for q in quotes]

problems.append({"slug": "other", "title": "Something else", "questions": []})
(SITE / "public" / "problems.json").write_text(json.dumps({"problems": problems}, indent=2) + "\n")

sql = ["-- Generated by scripts/sync-problems.py: starting voices from the problems' quotes."]
for slug, quote in seeds:
    q = quote.replace("'", "''")
    sql.append(
        "INSERT INTO voices (problem, text, text_key, voter_hash, ip_hash, source, approved, created_at) "
        f"SELECT '{slug}', '{q}', lower('{q}'), 'seed', 'seed', 'chat', 1, 1792108800000 "
        f"WHERE NOT EXISTS (SELECT 1 FROM voices WHERE problem = '{slug}' AND text_key = lower('{q}'));"
    )
(SITE / "seed.sql").write_text("\n".join(sql) + "\n")
print(f"{len(problems)} problems, {len(seeds)} seed voices")
