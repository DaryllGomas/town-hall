#!/usr/bin/env python3
"""Build site/public/problems.json and site/seed.sql from problems/*/README.md.

The repo's problem folders are the source of truth; run this after adding or editing one.
seed.sql adds each problem's "In people's words" quotes as starting voices (safe to re-run).
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SITE = ROOT / "site"


def front_matter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    fields = {}
    for line in (m.group(1) if m else "").splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "-")):
            fields[key.strip()] = value.strip()
    return fields, text[m.end():] if m else text


def section(body, name):
    m = re.search(rf"^##\s+{re.escape(name)}\s*$(.*?)(?=^##\s|\Z)", body, re.M | re.S)
    return m.group(1).strip() if m else ""


def plain(md):
    """Markdown paragraph -> plain text (links keep their words; emphasis markers dropped)."""
    md = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", md)
    return re.sub(r"\s+", " ", re.sub(r"[*_`]", "", md)).strip()


def plan(md, slug):
    """'## The solution' -> {goal, steps: [{who, text, evidence}], note}. Empty dict when the section is missing."""
    if not md:
        return {}
    goal = re.search(r"\*\*(.+?)\*\*", md, re.S)
    steps = []
    for item in re.findall(r"^\d+\.\s+(.+?)(?=^\d+\.\s|^\*[^*]|\Z)", md, re.M | re.S):
        item = re.sub(r"\s+", " ", item).strip()
        ev = re.search(r"\(\[[^\]]*\]\((solutions/[^)]+\.md)\)\)", item)
        who = re.match(r"\*\*(.+?)\*\*:?\s*", item)
        text = item[who.end():] if who else item
        text = re.sub(r"\s*\(\[[^\]]*\]\([^)]+\)\)", "", text)
        steps.append({
            "who": plain(who.group(1)).rstrip(":") if who else "",
            "text": plain(text).lstrip(": ").strip(),
            "evidence": f"{REPO_URL}problems/{slug}/{ev.group(1)}" if ev else "",
        })
    note = re.search(r"^\*([^*].+?)\*\s*$", md, re.M)
    g = re.sub(r"^goal:\s*", "", plain(goal.group(1)), flags=re.I) if goal else ""
    return {"goal": g[:1].upper() + g[1:], "steps": steps, "note": plain(note.group(1)) if note else ""}


REPO_URL = "https://github.com/DaryllGomas/town-hall/blob/main/"
problems, seeds = [], []
for readme in sorted(ROOT.glob("problems/*/README.md")):
    slug = readme.parent.name
    if slug.startswith("_"):
        continue
    fields, body = front_matter(readme.read_text())
    quotes = [q.strip() for q in re.findall(r"^>\s*(.+)$", section(body, "In people's words"), re.M)]
    questions = [q.strip() for q in re.findall(r"^-\s+(.+)$", section(body, "Open questions"), re.M)]
    problems.append({
        "slug": slug,
        "title": fields.get("title", slug),
        "questions": [q for q in questions if not q.lower().startswith("reminder")],
        "issue": plain(section(body, "The issue")),
        "plan": plan(section(body, "The solution"), slug),
    })
    # Quotes from the captured White House chat are "chat"; quotes from collected public posts are "post".
    source = "chat" if "data/chats" in readme.read_text().split("---")[1] else "post"
    seeds += [(slug, q, source) for q in quotes]

problems.append({"slug": "other", "title": "Something else", "questions": []})

# Researched fixes from problems/*/solutions/*.md go on the site as source 'repo', with who can act and a link.
REPO_URL = "https://github.com/DaryllGomas/town-hall/blob/main/"
fixes = []
for f in sorted(ROOT.glob("problems/*/solutions/*.md")):
    fields, body = front_matter(f.read_text())
    if fields.get("status") == "rejected" or f.parent.parent.name.startswith("_"):
        continue
    who = {}
    # Join wrapped bullet lines, so each bullet is one line.
    bullets = re.sub(r"\n[ \t]+(?=\S)", " ", section(body, "Who can make it happen"))
    for line in bullets.splitlines():
        m = re.match(r"^-\s+\*\*(.+?):?\*\*:?\s*(.+)$", line.strip())
        if m:
            label = m.group(1).rstrip(":").lower()
            key = "government" if label.startswith("gov") else "you" if label.startswith("you") else "means"
            who[key] = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", m.group(2)).strip()
    summary = re.sub(r"\s+", " ", re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", section(body, "Summary"))).strip()
    sources = len(re.findall(r"https://", section(body, "Sources")))
    fixes.append({
        "problem": f.parent.parent.name, "title": fields.get("title", f.stem), "body": summary,
        "detail": {"type": fields.get("type"), "status": fields.get("status"), "scale": fields.get("scale"),
                   "who": who, "sources": sources, "url": REPO_URL + str(f.relative_to(ROOT))},
    })
(SITE / "public" / "problems.json").write_text(json.dumps({"problems": problems}, indent=2) + "\n")

sql = ["-- Generated by scripts/sync-problems.py: starting voices from the problems' quotes."]
for slug, quote, source in seeds:
    q = quote.replace("'", "''")
    sql.append(
        "INSERT INTO voices (problem, text, text_key, voter_hash, ip_hash, source, approved, created_at) "
        f"SELECT '{slug}', '{q}', lower('{q}'), 'seed', 'seed', '{source}', 1, 1792108800000 "
        f"WHERE NOT EXISTS (SELECT 1 FROM voices WHERE problem = '{slug}' AND text_key = lower('{q}'));"
    )
def q(v):
    return "'" + str(v).replace("'", "''") + "'"


for fx in fixes:
    key = fx["title"].lower()
    detail = json.dumps(fx["detail"], ensure_ascii=False)
    sql.append(
        "INSERT INTO ideas (problem, title, body, title_key, voter_hash, ip_hash, source, approved, created_at, detail) "
        f"SELECT {q(fx['problem'])}, {q(fx['title'])}, {q(fx['body'])}, {q(key)}, 'repo', 'repo', 'repo', 1, 1792195200000, {q(detail)} "
        f"WHERE NOT EXISTS (SELECT 1 FROM ideas WHERE source = 'repo' AND title_key = {q(key)});"
    )
    # Keep the site in step with edits to the file.
    sql.append(f"UPDATE ideas SET problem = {q(fx['problem'])}, title = {q(fx['title'])}, body = {q(fx['body'])}, "
               f"detail = {q(detail)} WHERE source = 'repo' AND title_key = {q(key)};")
(SITE / "seed.sql").write_text("\n".join(sql) + "\n")
print(f"{len(problems)} problems, {len(seeds)} seed voices, {len(fixes)} researched fixes")
